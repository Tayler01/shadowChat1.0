const move = (id, x, y = 616, crouch = false) => ({ id, kind: 'move', x, y, crouch })
// Checkpoint activation starts at the lantern, beyond the move arrival tolerance.
const checkpoint = (name, x, crouch = false) => move(`checkpoint-${name}`, x + 24, 616, crouch)
const jump = (id, x, y = 616, fromY = 616) => ({ id, kind: 'jump', x, y, fromY, airJumpDelayMs: 350 })
const power = (pickupId, power, x) => ({ id: `power-${pickupId}`, kind: 'power', pickupId, power, x: x + 12, y: 616 })
const fight = (enemyId, minX, maxX, jumpStrike = true) => ({ id: `fight-${enemyId}`, kind: 'fight', enemyId, minX, maxX,
  ...(jumpStrike ? { jumpStrikeY: 616 } : {}), timeoutMs: 30000 })
const flame = (n, x) => ({ id: `relay-flame-${n}`, kind: 'relic', counter: 'objectiveItems', minCount: n, x, y: 616 })
const crownBeamDodge = { highId: 'relay-beam-crown-high', lowId: 'relay-beam-crown-low',
  minX: 17400, maxX: 18700, maxJumpX: 18560, groundY: 616 }
const crownGround = step => ({ ...step, beamDodge: crownBeamDodge })
const lockWest = step => ({ ...step, arrowDodge: { minX: 18940, maxX: 19480, groundY: 616 } })
const lockEast = step => ({ ...step, arrowDodge: { minX: 19960, maxX: 20700, groundY: 616 } })
const crawl = (n, x) => [move(`crawl-${n}-entry`, x - 40, 616, true), move(`crawl-${n}-exit`, x + 335, 616, true)]
const gap = (n, edge, landing) => [move(`gap-${n}-takeoff`, edge - 50), jump(`gap-${n}-landing`, landing + 50)]
const stairGap = (n, takeoffX, stepX, stepY, landingX) => [move(`gap-${n}-takeoff`, takeoffX),
  { ...jump(`gap-${n}-step`, stepX, stepY), riseBeforeMoveY: stepY + 40 },
  jump(`gap-${n}-landing`, landingX, 616, stepY)]
const phaseGap = (n, platformId, takeoffX, boardX, phaseY, landingX) => [
  move(`gap-${n}-takeoff`, takeoffX),
  { id: `gap-${n}-phase-cycle`, kind: 'phase-cycle', platformId, x: takeoffX, y: 616, crouch: true, timeoutMs: 5000 },
  { ...jump(`gap-${n}-phase-board`, boardX, phaseY), riseBeforeMoveY: phaseY - 6 },
  move(`gap-${n}-landing`, landingX),
]
const cover = (id, x, width) => [move(`${id}-approach`, x - 50),
  { ...jump(`${id}-top`, x + width / 2, 504), riseBeforeMoveY: 498 },
  move(`${id}-return`, x + width + 45)]

