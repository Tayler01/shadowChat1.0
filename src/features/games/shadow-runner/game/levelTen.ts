function platform(
  id: string,
  x: number,
  width: number,
  visualId = 'relay-wide-floor',
  y = FLOOR_Y,
  height = 76,
): ShadowRunnerRect {
  return { id, visualId, terrainSet: 'relay', x, y, width, height }
}

function coinLine(
  prefix: string,
  startX: number,
  count: number,
  spacing: number,
  y: number,
): ShadowRunnerPoint[] {
  return Array.from({ length: count }, (_, index) => ({
    id: `${prefix}-${index + 1}`,
    x: startX + index * spacing,
    y,
  }))
}

function coinPath(
  prefix: string,
  points: ReadonlyArray<readonly [x: number, y: number]>,
): ShadowRunnerPoint[] {
  return points.map(([x, y], index) => ({
    id: `${prefix}-${index + 1}`,
    x,
    y,
  }))
}

function curateCoinRoute(points: ShadowRunnerPoint[]) {
  return points.filter((_, index) => index % 3 !== 2)
}

function enemy(
  id: string,
  kind: ShadowRunnerEnemyConfig['kind'],
  x: number,
  patrolLeft: number,
  patrolRight: number,
  encounterId?: string,
  options: Partial<ShadowRunnerEnemyConfig> = {},
): ShadowRunnerEnemyConfig {
  const defaultHealth: Partial<Record<ShadowRunnerEnemyConfig['kind'], number>> = {
    'relay-lancer': 6,
    'prism-caster': 5,
    'gearwing-drone': 4,
    'sentry-sovereign': 24,
    'gate-pikeman': 6,
    'storm-grenadier': 4,
    'crypt-warden': 6,
    'rival-courier': 7,
    'tower-archer': 4,
    'moon-stalker': 4,
    'candle-jester': 4,
  }
  const health = options.health ?? defaultHealth[kind] ?? 3

  return {
    id,
    kind,
    x,
    y: FLOOR_Y,
    health,
    maxHealth: options.maxHealth ?? health,
    patrolLeft,
    patrolRight,
    direction: options.direction ?? -1,
    encounterId,
    ...options,
  }
}

